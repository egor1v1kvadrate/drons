"""Вкладка «Справка»: как работать с программой. Только текст, без логики."""
import customtkinter as ctk

from manager.widgets import set_text

HELP_TEXT = """\
КАК РАБОТАТЬ С ПРОГРАММОЙ

Программа состоит из двух окон, которые работают вместе:
  • КАРТА — симуляция полётов над Ижевском и проверка «свой-чужой»;
  • МЕНЕДЖЕР УЧЁТА (это окно) — реестр БПЛА, ремонт, списание, история полётов.
Если менеджер закрыт, его открывает кнопка «СИСТЕМА УЧЁТА» на карте.
Все данные хранятся в базе data/uav.db (SQLite).


1. МЕНЕДЖЕР УЧЁТА

Регистрация
  Введите заводской номер БПЛА и номера четырёх деталей (планер, ОЭС, АКБ, ДВС).
  Допустимы буквы, цифры, дефис и пробел, не длиннее 20 символов.
  После регистрации дрон сразу вылетает на карте и получает сессионный ID.

Ремонт
  Найдите БПЛА по заводскому номеру и замените нужную деталь.
  Номерной ID собирается из номеров деталей, поэтому после ремонта он меняется,
  текущий полёт прерывается, и дрон получает новый сессионный ID.

Каталог
  Все БПЛА реестра: заводской номер, номерной ID и текущая сессия.

Полёты
  История всех полётов. Поиск работает по сессионному ID, заводскому номеру
  или номерному ID.

Списание
  Удаляет БПЛА из реестра и переносит его в архив. Дрон исчезает с карты,
  его сессия закрывается со статусом «СПИСАН».


2. КАРТА

Цвета объектов
  ● зелёный — безопасно: подпись и сессионный ID подтверждены;
  ● жёлтый  — не проверено: проверка ещё идёт или доверие снижается;
  ● красный — опасно: проверка не пройдена, объект считается чужим;
  ● серый   — пропал с радара: отметки нет, объект летит «вслепую».

Подпись на карте
  У своих дронов — хвост сессионного ID, например S-…7E4D.
  У чужих — их имя: КРАСНЫЙ-1, ЖЁЛТЫЙ-1, П-ТРАНЗИТ.

Счётчик в правом верхнем углу карты
  Сколько сейчас своих, чужих, опасных и пропавших с радара объектов.

Панель «Информация об объекте»
  Щёлкните по объекту в списке слева. Самое важное (ID, модель,
  статус, маршрут) выделено светло-голубым.

Кнопки
  «ДОБАВИТЬ КРАСНЫЙ» / «ДОБАВИТЬ ЖЁЛТЫЙ» — создать учебный чужой объект.
  «ОТКРЫТЬ ЖУРНАЛ» — полный протокол событий, важные выделены красным.


3. КАК ЗАЩИЩЕНЫ ID (ДВА УРОВНЯ)

  1) Подпись HMAC. Станция посылает дрону случайный вызов, дрон отвечает
     подписанным сообщением. Без секретного ключа правильную подпись не подделать.
  2) Сессионный ID. На каждый полёт выдаётся новый случайный ID. Станция
     принимает ответ, только если этот ID активен и принадлежит именно этому
     дрону. Закрытый ID (полёт окончен, прерван, дрон списан) больше
     никогда не принимается — даже если злоумышленник украл ключ.
"""


class HelpTab:
    def __init__(self, frame, window):
        box = ctk.CTkTextbox(frame, font=("Courier", 12), wrap="word")
        box.pack(pady=10, fill="both", expand=True)
        set_text(box, HELP_TEXT)

    def refresh(self):
        pass  # текст справки не меняется
