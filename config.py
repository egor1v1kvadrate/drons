def _load_simulation_key() -> bytes:
    """Секретный ключ HMAC. В коде его НЕТ — иначе он утёк бы вместе с кодом.

    1) Если задана переменная окружения UAV_SIM_KEY — берём её.
    2) Иначе ключ лежит в data/.sim_key. При первом запуске он создаётся случайным
       (secrets — криптостойкий генератор) и дальше не меняется.
    Файл .sim_key внесён в .gitignore: на GitHub и в архивы он попадать не должен.
    """
    env_key = os.environ.get("UAV_SIM_KEY")
    if env_key:
        return env_key.encode()
    key_file = DATA_DIR / ".sim_key"
    if not key_file.exists():
        key_file.write_text(secrets.token_hex(32), encoding="ascii")
    return key_file.read_text(encoding="ascii").strip().encode()


